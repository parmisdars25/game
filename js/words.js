/**
 * استخراج فهرست کلمات بر اساس دسته‌بندی‌های انتخاب‌شده در لابی
 * @param {string[]} selectedCategories
 * @returns {Array<{word: string, category: string, categoryLabel: string}>}
 */
export function getWordPool(selectedCategories = ['all']) {
  const useAll = !Array.isArray(selectedCategories)
    || selectedCategories.length === 0
    || selectedCategories.includes('all');

  const keys = useAll
    ? Object.keys(WORD_BANK)
    : selectedCategories.filter((cat) => Array.isArray(WORD_BANK[cat]));

  const finalKeys = keys.length > 0 ? keys : Object.keys(WORD_BANK);
  const pool = [];

  for (const cat of finalKeys) {
    const label = CATEGORY_LABELS[cat] || cat;
    for (const word of WORD_BANK[cat]) {
      pool.push({ word, category: cat, categoryLabel: label });
    }
  }

  return pool;
}

/**
 * انتخاب تصادفی ۳ کلمه غیرتکراری برای شروع نوبت نقاش
 * اگر همه کلمات مصرف شده باشند، به صورت هوشمند از کل بانک مجدداً انتخاب می‌کند
 * @param {string[]} selectedCategories
 * @param {string[]} usedWords
 * @param {number} count
 */
export function pickWordChoices(selectedCategories = ['all'], usedWords = [], count = 3) {
  const pool = getWordPool(selectedCategories);
  const usedSet = new Set(Array.isArray(usedWords) ? usedWords : []);

  let available = pool.filter((item) => !usedSet.has(item.word));
  if (available.length < count) {
    // اگر کلمات مصرف‌نشده کمتر از تعداد درخواستی شد، کل استخر را بازنشانی می‌کنیم
    available = [...pool];
  }

  // الگوریتم Fisher-Yates برای انتخاب کاملاً عادلانه
  const copy = [...available];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }

  return copy.slice(0, Math.min(count, copy.length));
}

/**
 * پیدا کردن عنوان دسته‌بندی یک کلمه برای نمایش در رابط کاربری
 * @param {string} word
 * @returns {string}
 */
export function findCategoryForWord(word) {
  if (!word) return '';
  for (const [cat, list] of Object.entries(WORD_BANK)) {
    if (list.includes(word)) {
      return CATEGORY_LABELS[cat] || '';
    }
  }
  return '';
}
